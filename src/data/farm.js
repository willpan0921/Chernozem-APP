// WHAT THIS FILE DOES
// Everything the FIELD product shows about one farmer's farm: the farm
// itself, its seven fields, the recovery plan for Field 7, this week's next
// steps, scouting notes, satellite readings, downloads and the field
// settings. Every number and sentence on the Field pages comes from here,
// so the pages themselves hold no data.
//
// THIS IS PLACEHOLDER DATA. It copies the design mockups exactly so the app
// looks real while it is being built. The team will replace it with real
// data (from a database or an API) later, one export at a time.
//
// WHO EDITS IT
// Anyone changing what the Field pages say or show. You do not need to touch
// the page files to change a number, a date or a sentence.
//
// HOW TO EDIT IT
// - Each "export const ..." below is one block of data. The comment above it
//   says which screen uses it.
// - Dates come in two forms: an ISO date the computer can sort
//   ("2026-09-28") and a display string people read ("Sep 28"). Change both.
// - Keep the quotation marks around text and the comma after every entry.
// - "id" values are used to link things together (a note points to a field
//   by its id). Change them only if you change every place they are used.
// - A few blocks are generated by small helper functions at the bottom of
//   the file (the long NDVI history, for example). Edit the helper's inputs
//   rather than typing out hundreds of numbers.

