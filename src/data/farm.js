// Builds the long monthly NDVI history for the Data page. The curve is a
// smooth seasonal wave: low in winter (about 0.25), high in July (about
// 0.80). Field 7 follows the farm until "damageFrom", then its summer peak
// drops to about 0.42 (the mockup's July 2025 value).
function makeNdviHistory({ from, to, damageFrom }) {
  const [fromYear, fromMonth] = from.split("-").map(Number);
  const [toYear, toMonth] = to.split("-").map(Number);
  const [damageYear, damageMonth] = damageFrom.split("-").map(Number);

  // Tiny year-to-year differences so the waves do not all look identical.
  // 2025 is left exact so the highlight reads 0.80 / 0.42.
  const wobble = { 2019: 0.0, 2020: -0.02, 2021: 0.01, 2022: 0.0, 2023: -0.01, 2024: 0.02, 2025: 0.0, 2026: -0.01 };

  const points = [];
  const months = [];
  const farmAverage = [];
  const field7 = [];

  for (let year = fromYear; year <= toYear; year += 1) {
    const lastMonth = year === toYear ? toMonth : 12;
    const firstMonth = year === fromYear ? fromMonth : 1;
    for (let month = firstMonth; month <= lastMonth; month += 1) {
      const key = `${year}-${String(month).padStart(2, "0")}`;
      // 0 in January, 1 in July: a cosine wave that peaks in July.
      const season = (1 - Math.cos((2 * Math.PI * (month - 1)) / 12)) / 2;
      const w = wobble[year] || 0;

      const farmValue = round2(0.25 + (0.55 + w) * season);

      const damaged = year > damageYear || (year === damageYear && month >= damageMonth);
      // In the year of the damage the field is already weaker; afterwards it
      // settles at about half the farm's summer level.
      const field7Peak = !damaged ? 0.55 + w : year === damageYear ? 0.35 : 0.22 + w / 2;
      const field7Base = damaged ? 0.2 : 0.25;
      const field7Value = round2(field7Base + field7Peak * season);

      months.push(key);
      farmAverage.push(farmValue);
      field7.push(field7Value);
      points.push({
        month: key,
        year,
        monthIndex: month - 1,
        label: `${MONTH_SHORT[month - 1]} ${year}`,
        farmAverage: farmValue,
        field7: field7Value,
      });
    }
  }

  const years = [];
  for (let year = fromYear; year <= toYear; year += 1) years.push(year);

  return { from, to, months, farmAverage, field7, points, years };
}

// Rounds to two decimal places.
function round2(value) {
  return Math.round(value * 100) / 100;
}

// Returns the mid-point of every edge of a closed polygon.
function midpoints(corners) {
  return corners.map((corner, i) => {
    const next = corners[(i + 1) % corners.length];
    return { x: round2((corner.x + next.x) / 2), y: round2((corner.y + next.y) / 2) };
  });
}
