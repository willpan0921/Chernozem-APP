// Builds the "Plant health this season" chart data (April to October) from
// three short lists of seven numbers plus a marker for today.
function makeSeasonSeries({ thisSeason, normalLow, normalHigh, marker }) {
  const months = ["Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct"];
  const points = months.map((month, i) => ({
    month,
    date: `2026-${String(i + 4).padStart(2, "0")}-01`,
    value: thisSeason[i],
    normalLow: normalLow[i],
    normalHigh: normalHigh[i],
    // October has not happened yet: pages can draw it dotted.
    projected: i === months.length - 1,
  }));
  return {
    title: "Plant health this season",
    subtitle: "NDVI, Apr to Oct",
    axisLabels: ["Apr", "Jun", "Aug", "Oct"],
    yTicks: [0.25, 0.5, 0.75],
    points,
    marker: {
      ...marker,
      // Where "today" sits along the x axis, 0 = April, 1 = October.
      position: (5 + 27 / 30) / 6,
      normalDisplay: `Normal ${marker.normalLow.toFixed(2)} to ${marker.normalHigh.toFixed(2)}`,
    },
    legend: ["This season", "Normal range, 2019 to 2021"],
  };
}

